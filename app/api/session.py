"""Superseded pre-ADR-009 loopback bootstrap and browser-session authority.

This module owns no provider or tool capability.  In the pre-release development path,
the test deployment harness calls ``mint_bootstrap`` out of band, and only a same-origin
POST may exchange that capability for a short-lived cookie plus a separate CSRF value.
Session objects are live, identity-bound capabilities; constructing a dataclass with
copied fields does not authenticate it.

This harness-minted URL-fragment topology is retained only as historical loopback
feasibility evidence; it is not the current product boundary or release authentication
contract.  T025 replaces it with the self-hosted browser first-owner flow: a capability
generated by the inspectable offline deployment artifact, entered once in the browser
form and never placed in a URL, plus OriginProfile, durable session-root and recovery
design from ADR-010 through ADR-012.
"""

